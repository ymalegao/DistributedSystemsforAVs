#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# With / without RSU (intersection-unit) ablation matrix.
#
#   OFF = FourVehiclesResDB          (4 vehicles, N=4, f=1, no units)
#   ON  = FourVehiclesFourUnitsResDB (4 vehicles + 4 units, N=8, f=2)
#
# For each config we sweep k = 0,1,2 PBFT-silent replicas (omission faults on
# node[1..k], leaving the leader node[0] honest). The story:
#   OFF tolerates ⌊(4-1)/3⌋ = 1 fault  → commits at k=0,1, FAILS at k=2.
#   ON  tolerates ⌊(8-1)/3⌋ = 2 faults → commits at k=0,1,2  (the units save it).
#
# All runs use the fast channel (config_fast.xml, no obstacle shadowing) for speed.
# Must be run INSIDE the opp_env shell (needs OMNeT++ + SUMO).
#
#   opp_env shell -w /home/mathesh/Documents/vc omnetpp-6.2.0
#   benchmarks/rsu_ablation/run_matrix.sh [reps] [timeout_s]
# ─────────────────────────────────────────────────────────────────────────────
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
FOURWAY="$REPO/fourway"
RESULTS="$HERE/results"
FASTXML="$FOURWAY/config_fast.xml"
REPS="${1:-1}"
TIMEOUT="${2:-180}"
mkdir -p "$RESULTS"

gen_fault_ini() {   # $1 = k ; prints path to generated ini
  local k="$1" f="$RESULTS/_fault_k${1}.ini"
  {
    echo "# auto-generated by run_matrix.sh — k=${k} PBFT-silent replicas + fast channel"
    echo "[General]"
    echo "*.**.nic.phy80211p.analogueModels = xmldoc(\"${FASTXML}\")"
    # 5 ms bridge poll/tick (instead of the 1 ms default) applied uniformly to ALL
    # cells of the matrix, so OFF vs ON stay directly comparable. This is the
    # ResDB-thread -> OMNeT-event-loop hand-off rate; coarsening it trades a little
    # per-hop latency for ~4x wall-clock. Outcome metrics (commit success) are
    # unaffected; latency/overhead are measured under this same setting throughout.
    echo "*.node[*].appl.transportPollInterval = 0.005"
    echo "*.node[*].appl.timeTickInterval      = 0.005"
    echo "*.iu[*].appl.transportPollInterval   = 0.005"
    echo "*.iu[*].appl.timeTickInterval        = 0.005"
    local i
    for ((i=1; i<=k; i++)); do
      echo "*.node[${i}].appl.isByzantine = true"
      echo "*.node[${i}].appl.byzantinePbftSilent = true"
    done
  } > "$f"
  printf '%s\n' "$f"
}

run_one() {   # $1=label $2=config $3=k $4=rep
  local label="$1" config="$2" k="$3" rep="$4"
  local ini log rc
  ini="$(gen_fault_ini "$k")"
  log="$RESULTS/${label}_k${k}_rep${rep}.log"
  ( cd "$FOURWAY" && timeout "$TIMEOUT" \
      ./run-resdb-simulation.sh -f "$FOURWAY/omnetpp.ini" -f "$ini" \
        -u Cmdenv -c "$config" ) > "$log" 2>&1
  rc=$?
  echo "  ${label} k=${k} rep=${rep} exit=${rc} -> $(basename "$log")"
}

echo "=== RSU ablation matrix: reps=${REPS} timeout=${TIMEOUT}s ==="
for rep in $(seq 1 "$REPS"); do
  for k in 0 1 2; do
    run_one OFF FourVehiclesResDB          "$k" "$rep"
    run_one ON  FourVehiclesFourUnitsResDB "$k" "$rep"
  done
done
echo "ALL_DONE results in ${RESULTS}"
